# -----------------------------
# Check if graph is acyclic
# -----------------------------
def is_acyclic(graph):
    try:
        nx.find_cycle(graph, orientation="original")
        return False
    except nx.exception.NetworkXNoCycle:
        return True

# -----------------------------
# Exact FVS Search
# -----------------------------
def find_fvs(G):
    n = len(G.nodes())

    for k in range(n + 1):
        print(f"Trying size {k}...")
        for subset in itertools.combinations(G.nodes(), k):

            H = G.copy()
            H.remove_nodes_from(subset)

            if is_acyclic(H):
                return set(subset)

    return None


